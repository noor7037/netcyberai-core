'use client';

import { useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';
import { Input } from '@/components/ui/Input';
import { Select } from '@/components/ui/Select';
import { Button } from '@/components/ui/Button';
import { Badge } from '@/components/ui/Badge';

const STAGE_LABELS: Record<string, string> = {
  tenant_created: 'Tenant Created',
  admin_invited: 'Admin Invited',
  data_imported: 'Data Imported',
  data_validated: 'Data Validated',
  consent_collection: 'Consent Collection',
  configuration: 'Configuration',
  training: 'Training',
  pilot_outbound_approved: 'Pilot Outbound Approved',
  go_live: 'Go-Live',
};
const STAGE_ORDER = Object.keys(STAGE_LABELS);
const REQUIRED_PURPOSES = ['core_records', 'operational_communication'];
const INVITABLE_ROLES = ['school_admin', 'principal', 'teacher', 'accountant', 'academic_coordinator'];

interface ConsentSummary {
  totalStudents: number;
  grantedByPurpose: Record<string, number>;
  requiredComplete: boolean;
  percentComplete: number;
}

async function jsonOrError(res: Response) {
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error ?? `request failed (${res.status})`);
  return data;
}

export function SchoolOnboardingPanel({
  schoolId,
  initialStage,
  isPilot,
  pilotAllowOutbound,
}: {
  schoolId: string;
  initialStage: string;
  isPilot: boolean;
  pilotAllowOutbound: boolean;
}) {
  const router = useRouter();
  const [stage, setStage] = useState(initialStage);
  const [stageError, setStageError] = useState<string | null>(null);
  const [consent, setConsent] = useState<ConsentSummary | null>(null);
  const [features, setFeatures] = useState<Record<string, boolean>>({});
  const [flagName, setFlagName] = useState('');
  const [flagEnabled, setFlagEnabled] = useState(true);
  const [inviteEmail, setInviteEmail] = useState('');
  const [inviteName, setInviteName] = useState('');
  const [inviteRole, setInviteRole] = useState(INVITABLE_ROLES[0]);
  const [inviteStatus, setInviteStatus] = useState<string | null>(null);
  const [targetUserId, setTargetUserId] = useState('');
  const [reason, setReason] = useState('');
  const [impersonation, setImpersonation] = useState<{ impersonationId: string; expiresAt: string } | null>(null);
  const [impersonateStatus, setImpersonateStatus] = useState<string | null>(null);

  async function loadConsent() {
    const res = await fetch(`/api/control/schools/${schoolId}/consent-summary`);
    setConsent(await jsonOrError(res).catch(() => null));
  }
  async function loadFeatures() {
    const res = await fetch(`/api/control/schools/${schoolId}/features`);
    const data = await jsonOrError(res).catch(() => ({ enabledFeatures: {} }));
    setFeatures(data.enabledFeatures ?? {});
  }

  useEffect(() => {
    loadConsent();
    loadFeatures();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [schoolId]);

  const nextStage = STAGE_ORDER[STAGE_ORDER.indexOf(stage) + 1];

  async function advanceStage() {
    setStageError(null);
    try {
      const data = await jsonOrError(
        await fetch(`/api/control/schools/${schoolId}/stage`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ toStage: nextStage }),
        })
      );
      setStage(data.school.onboarding_stage);
      router.refresh();
    } catch (err) {
      setStageError(err instanceof Error ? err.message : 'advance failed');
    }
  }

  async function toggleFlag(e: React.FormEvent) {
    e.preventDefault();
    await jsonOrError(
      await fetch(`/api/control/schools/${schoolId}/features`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ feature: flagName, enabled: flagEnabled }),
      })
    );
    setFlagName('');
    loadFeatures();
  }

  async function submitInvite(e: React.FormEvent) {
    e.preventDefault();
    setInviteStatus(null);
    try {
      await jsonOrError(
        await fetch(`/api/control/schools/${schoolId}/invite`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ email: inviteEmail, displayName: inviteName, role: inviteRole }),
        })
      );
      setInviteStatus(`Invited ${inviteEmail} as ${inviteRole}. Supabase sent a one-time email link -- no password was ever generated by this app.`);
      setInviteEmail('');
      setInviteName('');
    } catch (err) {
      setInviteStatus(err instanceof Error ? err.message : 'invite failed');
    }
  }

  async function startImpersonation(e: React.FormEvent) {
    e.preventDefault();
    setImpersonateStatus(null);
    try {
      const data = await jsonOrError(
        await fetch('/api/control/impersonate/start', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ targetUserId, reason }),
        })
      );
      setImpersonation({ impersonationId: data.impersonationId, expiresAt: data.expiresAt });
      setImpersonateStatus(`Started. Time-boxed to ${new Date(data.expiresAt).toLocaleTimeString()}. Logged as ImpersonationStarted, visible in this school's own audit trail.`);
    } catch (err) {
      setImpersonateStatus(err instanceof Error ? err.message : 'impersonation failed to start');
    }
  }

  async function endImpersonation() {
    await fetch('/api/control/impersonate/end', { method: 'POST' });
    setImpersonation(null);
    setImpersonateStatus('Ended. Logged as ImpersonationEnded.');
  }

  return (
    <div className="flex flex-col gap-8">
      <section>
        <h3 className="mb-2 text-base font-bold text-slate">Onboarding stage</h3>
        <div className="flex items-center gap-3">
          <Badge variant="neutral">{STAGE_LABELS[stage] ?? stage}</Badge>
          {nextStage && (
            <Button variant="outline" onClick={advanceStage}>
              Advance to {STAGE_LABELS[nextStage]}
            </Button>
          )}
        </div>
        {stage === 'training' && (
          <p className="mt-2 text-sm text-amber-text">
            The next step, Pilot Outbound Approved, is specified as a principal's own approval (PRD §7.2), not a
            platform-admin action. [GAP] this wizard records the transition but does not yet route the actual
            approval to the school's own principal in Platform 3 -- flagged, not silently assumed.
          </p>
        )}
        {stageError && <p className="mt-2 text-sm text-red-800">{stageError}</p>}
      </section>

      <section>
        <h3 className="mb-2 text-base font-bold text-slate">Pilot status</h3>
        <p className="text-sm text-slate">
          is_pilot: <strong>{String(isPilot)}</strong> · pilot_allow_outbound: <strong>{String(pilotAllowOutbound)}</strong>
        </p>
        <p className="mt-1 text-sm text-slate/70">
          No control here sets either flag. Disabling pilot mode is a separate, deliberate, logged action outside
          onboarding (Task 3) -- there is intentionally nothing to click.
        </p>
      </section>

      <section>
        <h3 className="mb-2 text-base font-bold text-slate">Consent completion</h3>
        {!consent ? (
          <p className="text-sm text-slate/70">Loading...</p>
        ) : (
          <>
            <div className="mb-2 h-3 w-full overflow-hidden rounded-full bg-slate/10">
              <div
                className={`h-full ${consent.requiredComplete ? 'bg-emerald-text' : 'bg-sapphire'}`}
                style={{ width: `${consent.percentComplete}%` }}
              />
            </div>
            <p className="text-sm text-slate">
              {consent.percentComplete}% complete across {consent.totalStudents} student(s), required purposes only.
            </p>
            <ul className="mt-1 text-sm text-slate/70">
              {REQUIRED_PURPOSES.map((p) => (
                <li key={p}>
                  {p}: {consent.grantedByPurpose[p] ?? 0} / {consent.totalStudents}
                </li>
              ))}
            </ul>
            <p className="mt-2 text-sm text-red-800">
              There is no bulk-mark-consent action anywhere in this product. Staff clearing this meter by marking
              consent that was never actually collected creates worse exposure than an honest incomplete state.
            </p>
          </>
        )}
      </section>

      <section>
        <h3 className="mb-2 text-base font-bold text-slate">Feature flags</h3>
        <p className="mb-2 text-sm text-slate/70">
          Current: <code>{JSON.stringify(features)}</code>
        </p>
        <form onSubmit={toggleFlag} className="flex flex-wrap items-end gap-3">
          <Input id="flag-name" label="Feature name" value={flagName} onChange={(e) => setFlagName(e.target.value)} required />
          <Select
            id="flag-enabled"
            label="Enabled"
            value={flagEnabled ? 'true' : 'false'}
            onChange={(e) => setFlagEnabled(e.target.value === 'true')}
          >
            <option value="true">true</option>
            <option value="false">false</option>
          </Select>
          <Button type="submit" variant="outline">
            Save flag
          </Button>
        </form>
      </section>

      <section>
        <h3 className="mb-2 text-base font-bold text-slate">Invite staff</h3>
        <form onSubmit={submitInvite} className="flex flex-col gap-3 md:flex-row md:items-end md:gap-3">
          <Input id="invite-email" label="Email" type="email" value={inviteEmail} onChange={(e) => setInviteEmail(e.target.value)} required />
          <Input id="invite-name" label="Display name" value={inviteName} onChange={(e) => setInviteName(e.target.value)} required />
          <Select id="invite-role" label="Role" value={inviteRole} onChange={(e) => setInviteRole(e.target.value)}>
            {INVITABLE_ROLES.map((r) => (
              <option key={r} value={r}>
                {r}
              </option>
            ))}
          </Select>
          <Button type="submit">Send invite</Button>
        </form>
        {inviteStatus && <p className="mt-2 text-sm text-slate">{inviteStatus}</p>}
      </section>

      <section>
        <h3 className="mb-2 text-base font-bold text-slate">Impersonation</h3>
        {!impersonation ? (
          <form onSubmit={startImpersonation} className="flex flex-col gap-3 md:flex-row md:items-end">
            <Input id="target-user-id" label="Target user_id" value={targetUserId} onChange={(e) => setTargetUserId(e.target.value)} required />
            <Input id="reason" label="Reason (required before access is granted)" value={reason} onChange={(e) => setReason(e.target.value)} required />
            <Button type="submit" variant="outline">
              Start impersonation
            </Button>
          </form>
        ) : (
          <Button variant="outline" onClick={endImpersonation}>
            End impersonation
          </Button>
        )}
        {impersonateStatus && <p className="mt-2 text-sm text-slate">{impersonateStatus}</p>}
      </section>
    </div>
  );
}

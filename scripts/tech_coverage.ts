// The Tech & AI Lab teaching-standard report (C557): every lesson file graded against the checks a reviewer can make from
// the file itself (src/lib/family/tech/validate.ts auditLesson), written to docs/family-app/tech-lab/COVERAGE.md.
// It reads only the repository.
//
//   npx tsx scripts/tech_coverage.ts            write the report
//   npx tsx scripts/tech_coverage.ts --check    fail when the report is out of date

import fs from 'fs';
import path from 'path';
import { courseCatalog, lessonById } from '../src/lib/family/tech/catalog';
import { pick } from '../src/lib/family/tech/text';
import { auditLesson, lessonProblems, type LessonAudit } from '../src/lib/family/tech/validate';

const out = path.join(process.cwd(), 'docs/family-app/tech-lab/COVERAGE.md');
const catalog = courseCatalog();
const rows: { unit: string; strand: string; audit: LessonAudit }[] = [];
const problems: string[] = [];
for (const unit of catalog.units) {
  for (const row of unit.lessons) {
    const lesson = lessonById(row.key);
    if (!lesson) continue;
    problems.push(...lessonProblems(lesson));
    rows.push({ unit: pick('en', unit.title), strand: unit.strand, audit: auditLesson(lesson) });
  }
}
const count = (f: (a: LessonAudit) => boolean) => rows.filter((r) => f(r.audit)).length;
const pictures = rows.reduce((n, r) => n + r.audit.pictures, 0);
const drawn = rows.reduce((n, r) => n + r.audit.drawn, 0);
const byLevel = [1, 2, 3].map((level) => {
  const mine = rows.filter((r) => r.audit.id.startsWith(`L${level}.`));
  return `| Level ${level} | ${mine.length} | ${mine.filter((r) => r.audit.grade === 'meets').length} | ${mine.filter((r) => r.audit.grade === 'minor').length} | ${mine.filter((r) => r.audit.grade === 'restructure').length} | ${mine.reduce((n, r) => n + r.audit.drawn, 0)} / ${mine.reduce((n, r) => n + r.audit.pictures, 0)} |`;
});
const lines = [
  '# Tech & AI Lab: teaching-standard coverage',
  '',
  'Generated by `npx tsx scripts/tech_coverage.ts` from the lesson files (C557). Each lesson is checked for what a reviewer',
  'can see in the file: a lesson-specific real-life opening, a prediction, pictures drawn (not stand-ins), narration tied to',
  'the part being explained, more than one Understand card, more than one kind of question, a lab, and a teach-back.',
  'It cannot judge accuracy or teaching quality by itself: a lesson marked "meets" still needs a subject review.',
  '',
  '- **meets**: opening, prediction, teach-back, and every picture drawn.',
  '- **minor**: every picture drawn, or at most three gaps.',
  '- **restructure**: more than three gaps and pictures still to draw.',
  '',
  `Lessons: **${rows.length}** in ${catalog.units.length} units. Meets: ${count((a) => a.grade === 'meets')}. Minor: ${count((a) => a.grade === 'minor')}. Restructure: ${count((a) => a.grade === 'restructure')}.`,
  `Pictures drawn: ${drawn} of ${pictures} See steps (the rest show an honest stand-in: a lab card, code, or the step's key idea).`,
  `Lessons with a lesson-specific opening: ${count((a) => a.hook)}; prediction: ${count((a) => a.predict)}; teach-back: ${count((a) => a.teachBack)}; narration tied to a part: ${count((a) => a.beats)}; a lab: ${count((a) => a.lab)}.`,
  `File problems (unknown picture kinds, incomplete languages, broken diagram references): ${problems.length}.`,
  '',
  '| Level | Lessons | Meets | Minor | Restructure | Pictures drawn |',
  '| --- | --- | --- | --- | --- | --- |',
  ...byLevel,
  '',
  '## Every lesson',
  '',
  '| Lesson | Unit | Grade | Opening | Predict | Teach-back | Pictures drawn | Tied narration | Understand | Questions (kinds) | Gaps |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map(({ unit, audit: a }) => `| ${a.id} | ${unit} | ${a.grade} | ${a.hook ? 'yes' : '—'} | ${a.predict ? 'yes' : '—'} | ${a.teachBack ? 'yes' : '—'} | ${a.drawn} / ${a.pictures} | ${a.beats ? 'yes' : '—'} | ${a.understand} | ${a.questions} (${a.questionKinds}) | ${a.gaps.join('; ') || '—'} |`),
  '',
];
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (now !== text) {
    console.error('docs/family-app/tech-lab/COVERAGE.md is out of date: run npx tsx scripts/tech_coverage.ts');
    process.exit(1);
  }
  console.log('Tech Lab coverage report is current.');
} else {
  fs.writeFileSync(out, text);
  console.log(lines.slice(11, 15).join('\n'));
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
